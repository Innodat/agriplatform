#!/usr/bin/env python3
"""Generate the pinned offline reference inventory and its identical browser copy."""
import argparse
import ast
import hashlib
import json
from pathlib import Path
APP=Path(__file__).resolve().parents[2]
HEBREW_SHA='c2d8e9e565be4ee69f938b444e5e0dc37fdfd0d9ccb185d1a5f8d95fab91c498'

def canonical(value):return json.dumps(value,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()

def build():
 source=APP/'scripts/hebrew.json'
 if hashlib.sha256(source.read_bytes()).hexdigest()!=HEBREW_SHA:raise ValueError('Pinned Hebrew source changed')
 metadata=next(ast.literal_eval(node.value) for node in ast.parse((APP/'backend/corpus_source.py').read_text()).body if isinstance(node,ast.AnnAssign) and isinstance(node.target,ast.Name) and node.target.id=='BOOK_METADATA')
 corpus=json.loads(source.read_bytes());nt_raw=(APP/'data/reference-catalogue/nt-verse-counts.json').read_bytes()
 if hashlib.sha256(nt_raw).hexdigest()!='989a7cf6873684784891b3fc9168ac247946c612fb987e182251216ddcdd7936':raise ValueError('Pinned NT inventory changed')
 nt=json.loads(nt_raw)
 books=[]
 for meta in metadata:
  books.append({'book_id':meta['osis_id'],'corpus_id':meta['id'],'name_en':meta['name_en'],'name_he':meta['name_he'],'division':meta['division'],'chapter_verse_counts':[len(chapter) for chapter in corpus[meta['name_en']]],'versification_id':'oshb-hebrew-json-c2d8e9e5','text_support':'hebrew_corpus'})
 for book in nt['books']:books.append({**book,'corpus_id':None,'name_he':None,'division':'new_testament','versification_id':nt['versification_id'],'text_support':'reference_only'})
 for book in books:
  aliases=[book['book_id'],book['name_en']]
  if book['name_he']:aliases.append(book['name_he'])
  for roman,number in [('III','3'),('II','2'),('I','1')]:
   if book['name_en'].startswith(roman+' '):aliases.append(number+book['name_en'][len(roman):]);break
  aliases.extend({'Ps':['Psalm','Ps','תהלים','תהילים'],'Song':['Song of Songs'],'Matt':['מתי']}.get(book['book_id'],[]))
  book['aliases']=list(dict.fromkeys(aliases))
 result={'generated_file_warning':'Generated by tools/py/build_reference_catalogue.py; do not edit.','catalogue_id':'scribeswell.references.v1','provenance':{'hebrew':{'path':'scripts/hebrew.json','sha256':HEBREW_SHA},'nt':{k:nt[k] for k in ('source_url','source_sha256','description')}},'books':books}
 result['catalogue_version']=hashlib.sha256(canonical(result)).hexdigest()
 return result

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 try:result=build()
 except ValueError as error:parser.exit(1,str(error)+'\n')
 raw=(json.dumps(result,ensure_ascii=False,indent=2)+'\n').encode()
 paths=['data/reference-catalogue/catalogue.json','web/src/generated/reference-catalogue.json']
 for relative in paths:
  path=APP/relative
  if args.check:
   if not path.is_file() or path.read_bytes()!=raw:parser.exit(1,'Reference catalogue drift: '+relative+'\n')
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
 manifest=APP/'data/reference-catalogue/.generated-files.json'
 content=(json.dumps({'generator':'tools/py/build_reference_catalogue.py','files':paths},indent=2)+'\n').encode()
 if args.check:
  if not manifest.is_file() or manifest.read_bytes()!=content:parser.exit(1,'Reference ownership manifest drift\n')
 else:manifest.write_bytes(content)
if __name__=='__main__':main()
